  await page.getByRole('button',{name:'Agregar concepto 101',exact:true}).click();await page.getByRole('button',{name:'CONTINUAR',exact:true}).click();await page.getByRole('button',{name:'CONFIRMAR PAGO DEMO',exact:true}).click()
  await expect(page.getByRole('heading',{name:'PAGO DEMO COMPLETADO'})).toBeVisible()
  await page.getByRole('button',{name:'ENVIAR POR CORREO',exact:true}).click()
  await page.getByLabel('Tu correo',{exact:true}).fill('secreto-personal@example.invalid')
  await page.getByRole('button',{name:'x',exact:true}).click()
  await page.getByLabel('Tu correo',{exact:true}).fill('secreto-personal@example.invalid')
  await page.getByLabel('Confirma tu correo',{exact:true}).fill('secreto-personal@example.invalid')
  await page.getByRole('button',{name:'REVISAR DESTINATARIO'}).click();await page.getByRole('button',{name:'CONFIRMAR Y ENVIAR'}).click()
