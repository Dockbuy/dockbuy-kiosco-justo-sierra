test('keyboard activation is a single interaction and has no invented touch coordinates',async({page})=>{
  await login(page)
  const button=page.getByRole('button',{name:/Servicios y pagos/});await button.focus();await page.keyboard.press('Enter')
  await expect(page.getByRole('button',{name:'Agregar concepto 101',exact:true})).toBeVisible()
  const trace=await inspect(page),clicks=trace.events.filter(e=>e.type==='interaction')
  expect(clicks).toHaveLength(1);expect(clicks[0].input).toBe('keyboard');expect(clicks[0].position).toBeUndefined()
})

test('a touchscreen tap produces one action with touch coordinates',async({browser})=>{
  const context=await browser.newContext({baseURL:'http://127.0.0.1:1421',hasTouch:true,viewport:{width:1366,height:900}})
  try{
    const page=await context.newPage();await login(page)
    await page.getByRole('button',{name:/Servicios y pagos/}).tap()
    await expect(page.getByRole('button',{name:'Agregar concepto 101',exact:true})).toBeVisible()
    const trace=await inspect(page),clicks=trace.events.filter(e=>e.type==='interaction')
    expect(clicks).toHaveLength(1);expect(clicks[0].input).toBe('touch')
    expect(clicks[0].position.x).toBeGreaterThan(0);expect(clicks[0].position.y).toBeLessThanOrEqual(1)
  }finally{await context.close()}
})
