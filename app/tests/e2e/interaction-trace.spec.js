import {test,expect} from '@playwright/test'
test.skip(process.env.TEST_TRACE_MODE!=='1','El visor solo existe en modo de desarrollo trace.')
test.beforeEach(async({request})=>{await request.post('http://127.0.0.1:8878/__test/reset',{data:{}})})
async function login(page){await page.goto('/');await page.getByRole('button',{name:'INGRESAR AL PORTAL'}).click();await page.getByRole('button',{name:'ENTRAR',exact:true}).click();await expect(page.getByRole('button',{name:/Servicios y pagos/})).toBeVisible()}
async function inspect(page){await page.getByRole('button',{name:/TRAZABILIDAD · DESARROLLO/}).click();await page.getByRole('button',{name:'Contrato JSON',exact:true}).click();return JSON.parse(await page.getByTestId('trace-json').innerText())}
async function close(page){await page.getByRole('button',{name:'Cerrar trazabilidad',exact:true}).click()}

test('records ordered actions, payment results, steps and logout without a telemetry request',async({page})=>{
  const network=[];page.on('request',request=>{if(['fetch','xhr'].includes(request.resourceType()))network.push(request.url())})
  await login(page)
  await page.getByRole('button',{name:/Servicios y pagos/}).click()
  await page.getByRole('button',{name:'Agregar concepto 101',exact:true}).click()
  await page.getByRole('button',{name:'Agregar concepto 102',exact:true}).click()
  await page.getByRole('button',{name:'Devolver concepto 102',exact:true}).click()
  await page.getByRole('button',{name:'CONTINUAR',exact:true}).click()
  await page.getByRole('button',{name:'CONFIRMAR PAGO DEMO',exact:true}).click()
  await expect(page.getByRole('heading',{name:'PAGO DEMO COMPLETADO'})).toBeVisible()
  await page.getByRole('button',{name:'FINALIZAR Y SALIR',exact:true}).click()
  const trace=await inspect(page)
  const actions=trace.events.filter(e=>e.type==='interaction').map(e=>e.action)
  expect(actions).toEqual(['nav.charges','payment.add','payment.add','payment.remove','payment.review','payment.confirm','session.exit'])
  expect(trace.events.some(e=>e.type==='operation.end'&&e.operation==='payment.simulate'&&e.outcome==='ok')).toBeTruthy()
  expect(trace.events.filter(e=>e.type==='screen.enter'&&e.screen==='charges').map(e=>e.step)).toEqual(expect.arrayContaining(['select','review','processing','receipt']))
  expect(trace.events.at(-1).type).toBe('session.end')
  expect(trace.events.map(e=>e.sequence)).toEqual(trace.events.map((_,i)=>i+1))
  expect(network.some(url=>/\/api\/(trace|telemetry|interactions)/.test(url))).toBeFalsy()
  await page.getByRole('button',{name:'Mapa de toques',exact:true}).click()
  await expect(page.locator('.trace-dot')).toHaveCount(actions.length)
  await page.screenshot({path:'test-results/trace-map.png',fullPage:true})
  await page.getByRole('button',{name:'Secuencia',exact:true}).click()
  await page.screenshot({path:'test-results/trace-timeline.png',fullPage:true})
  await close(page);await page.getByRole('button',{name:'INGRESAR AL PORTAL'}).click()
  const unchanged=await inspect(page);expect(unchanged.events).toEqual(trace.events)
})

