import {test,expect} from '@playwright/test'
import {PNG} from 'pngjs'
import jsQR from 'jsqr'

test.beforeEach(async({request})=>{await request.post('http://127.0.0.1:8878/__test/reset')})
async function login(page){
  await page.goto('/')
  await page.getByRole('button',{name:'INGRESAR AL PORTAL'}).click()
  await page.getByRole('button',{name:'ENTRAR',exact:true}).click()
  await page.getByRole('button',{name:/Servicios y pagos/}).click()
  await expect(page.getByRole('button',{name:'Agregar concepto 45',exact:true})).toBeEnabled()
}

test('ordered cart, cancellation, simulated payment, decoded QR and persistent invoice',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await login(page)
  await expect(page.getByRole('button',{name:'Agregar concepto 36',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Agregar concepto 45',exact:true}).click()
  await expect(page.locator('[data-concept-id="45"]')).toHaveCount(0)
  await expect(page.locator('[data-cart-id="45"]')).toBeVisible()
  await page.getByRole('button',{name:'Agregar concepto 36',exact:true}).click()
  await expect(page.getByRole('button',{name:'Devolver concepto 45',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Devolver concepto 36',exact:true}).click()
  await expect(page.locator('[data-concept-id="36"]')).toBeVisible()
  await page.getByRole('button',{name:'Cancelar toda la selección'}).click()
  await expect(page.locator('[data-cart-id]')).toHaveCount(0)
  await page.getByRole('button',{name:'Agregar concepto 45',exact:true}).click()
  await page.getByRole('button',{name:'Agregar concepto 36',exact:true}).click()
  await page.screenshot({path:'test-results/cart.png',fullPage:true})
  const catalog=await page.locator('.available-charges').boundingBox(),cart=await page.locator('.payment-cart').boundingBox()
  expect(catalog.width/cart.width).toBeGreaterThan(1.9)
  expect(catalog.width/cart.width).toBeLessThan(2.1)
  await page.getByRole('button',{name:'CONTINUAR',exact:true}).click()
  await expect(page.getByRole('heading',{name:'PAGO DEMO COMPLETADO'})).toBeVisible()
  await expect(page.locator('.receipt-total')).toContainText('5,525.00')
  await expect(page.locator('.receipt-qr')).toBeVisible()
  const src=await page.locator('.receipt-qr').getAttribute('src')
  const png=PNG.sync.read(Buffer.from(src.split(',')[1],'base64'))
  const decoded=jsQR(new Uint8ClampedArray(png.data),png.width,png.height)
  expect(decoded.data).toMatch(/^JS-PAY-[A-F0-9]{32}$/)
  await page.screenshot({path:'test-results/receipt.png',fullPage:true})
  await page.keyboard.type(decoded.data,{delay:8});await page.keyboard.press('Enter')
  await expect(page.getByRole('heading',{name:'FACTURAR',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'COMPROBANTE ENCONTRADO'})).toBeVisible()
  await page.getByRole('button',{name:'GENERAR E IMPRIMIR FACTURA DE PRUEBA'}).click()
  await expect(page.getByRole('heading',{name:'FACTURA DE PRUEBA GENERADA'})).toBeVisible()
  const folio=await page.locator('.receipt-card').innerText()
  await page.screenshot({path:'test-results/invoice.png',fullPage:true})
  await page.emulateMedia({media:'print'})
  await page.screenshot({path:'test-results/invoice-print.png',fullPage:true})
  await expect(page.locator('.print-document')).toBeVisible()
  await page.emulateMedia({media:'screen'})
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'XML DE PRUEBA'}).click()
  const download=await downloadPromise
  expect(download.suggestedFilename()).toContain('SIN-VALIDEZ-FISCAL.xml')
  await page.getByRole('button',{name:'FINALIZAR',exact:true}).click()
  await page.keyboard.type(decoded.data,{delay:8});await page.keyboard.press('Enter')
  await expect(page.getByRole('heading',{name:'FACTURA DE PRUEBA GENERADA'})).toBeVisible()
  await expect(page.locator('.receipt-card')).toHaveText(folio.replace(/\s+/g,' ').trim(),{useInnerText:true})
  expect(errors).toEqual([])
})

test('expired session returns to login with visible message',async({page})=>{
  await login(page)
  await page.getByRole('button',{name:'Agregar concepto 45',exact:true}).click()
  await page.route('**/api/payments/simulate',route=>route.fulfill({status:401,contentType:'application/json',body:JSON.stringify({error:'Sesión vencida'})}))
  await page.getByRole('button',{name:'CONTINUAR',exact:true}).click()
  await expect(page.getByText('Tu sesión venció. Vuelve a ingresar.')).toBeVisible()
  await expect(page.getByRole('button',{name:'ENTRAR',exact:true})).toBeVisible()
})

test('late payment response cannot reopen a closed session',async({page})=>{
  await login(page)
  await page.getByRole('button',{name:'Agregar concepto 45',exact:true}).click()
  let release;const gate=new Promise(resolve=>release=resolve)
  await page.route('**/api/payments/simulate',async route=>{const response=await route.fetch();await gate;try{await route.fulfill({response})}catch{}})
  await page.getByRole('button',{name:'CONTINUAR',exact:true}).click()
  await expect(page.getByRole('heading',{name:'SIMULANDO EL COBRO'})).toBeVisible()
  await page.getByRole('button',{name:'SALIR',exact:true}).click();release()
  await expect(page.getByRole('button',{name:'INGRESAR AL PORTAL'})).toBeVisible()
  await page.waitForTimeout(1000)
  await expect(page.getByRole('heading',{name:'PAGO DEMO COMPLETADO'})).toHaveCount(0)
})

test('HTML health response does not claim API is connected',async({page})=>{
  await page.route('**/api/health',route=>route.fulfill({status:200,contentType:'text/html',body:'<html>fallback</html>'}))
  await login(page)
  await expect(page.getByText('API DESCONECTADA')).toBeVisible()
})

test('1366x768 kiosk keeps continue accessible with four selected concepts',async({page})=>{
  await page.setViewportSize({width:1366,height:768})
  await login(page)
  for(const id of [45,36,55,56])await page.getByRole('button',{name:`Agregar concepto ${id}`,exact:true}).click()
  await expect.poll(()=>page.locator('.cart-items').evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  const button=await page.getByRole('button',{name:'CONTINUAR',exact:true}).boundingBox()
  expect(button.y+button.height).toBeLessThanOrEqual(768)
  await page.screenshot({path:'test-results/cart-kiosk.png',fullPage:true})
})
